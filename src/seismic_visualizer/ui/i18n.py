_TRANSLATIONS: dict[str, dict[str, str]] = {"en": _EN, "uk": _UK}


class LanguageManager(QObject):
    """Singleton that stores the current UI language and notifies on change."""

    language_changed = pyqtSignal(str)
    _instance: LanguageManager | None = None

    def __init__(self) -> None:
        super().__init__()
        self._language: str = "en"

    @classmethod
    def instance(cls) -> LanguageManager:
        if cls._instance is None:
            cls._instance = cls()
        return cls._instance

    def set_language(self, lang: str) -> None:
        if lang != self._language:
            self._language = lang
            self.language_changed.emit(lang)

    def language(self) -> str:
        return self._language


def tr(key: str) -> str:
    """Return the translation for *key* in the current UI language."""
    lang = LanguageManager.instance().language()
    table = _TRANSLATIONS.get(lang, _EN)
    return table.get(key, _EN.get(key, key))
